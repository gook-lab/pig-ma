// Map language to builtins
export const LANGUAGE_BUILTINS: Record<
  string,
  { globals: string[]; constructors: string[]; methods: string[] }
> = {
  javascript: JS_BUILTINS,
  typescript: JS_BUILTINS,
  python: PYTHON_BUILTINS,
  java: JAVA_BUILTINS,
  go: GO_BUILTINS,
  rust: RUST_BUILTINS,
  c: C_BUILTINS,
  cpp: C_BUILTINS,
  csharp: JAVA_BUILTINS, // Similar to Java
  ruby: RUBY_BUILTINS,
  php: JS_BUILTINS, // Similar patterns
  swift: JS_BUILTINS, // Similar patterns
  kotlin: JAVA_BUILTINS, // Similar to Java
};

/**
 * Enhance highlighted HTML with additional built-in highlighting
 */
export function enhanceHighlighting(html: string, language: string): string {
  const builtins = LANGUAGE_BUILTINS[language];
  if (!builtins) return html;

  let result = html;

  // Create sets for faster lookup
  const globalsSet = new Set(builtins.globals);
  const constructorsSet = new Set(builtins.constructors);
  const methodsSet = new Set(builtins.methods);

  // Replace untagged words that match builtins
  // Match words that are not already inside a span tag
  result = result.replace(
    /(?<=>)([a-zA-Z_$][a-zA-Z0-9_$]*)(?=<|[.\s()\[\]{},;:]|$)/g,
    (match, word) => {
      if (globalsSet.has(word)) {
        return `<span class="hljs-built_in">${word}</span>`;
      }
      if (constructorsSet.has(word)) {
        return `<span class="hljs-type">${word}</span>`;
      }
      return match;
    },
  );

  // Also match at the start of the string
  result = result.replace(
    /^([a-zA-Z_$][a-zA-Z0-9_$]*)(?=<|[.\s()\[\]{},;:])/,
    (match, word) => {
      if (globalsSet.has(word)) {
        return `<span class="hljs-built_in">${word}</span>`;
      }
      if (constructorsSet.has(word)) {
        return `<span class="hljs-type">${word}</span>`;
      }
      return match;
    },
  );

  // Highlight method calls (word followed by parenthesis)
  // This is tricky because we need to avoid double-wrapping
  // We'll look for .methodName( patterns
  result = result.replace(
    /\.([a-zA-Z_$][a-zA-Z0-9_$]*)\(/g,
    (match, methodName) => {
      if (methodsSet.has(methodName)) {
        return `.<span class="hljs-property">${methodName}</span>(`;
      }
      return match;
    },
  );

  return result;
}
